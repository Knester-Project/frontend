type EmojiPickerProps = {
    onPick: (emoji: string) => void;
    onClose: () => void;
};

export default function EmojiPicker({ onPick, onClose }: EmojiPickerProps) {

    const [activeCat, setActiveCat] = useState<EmojiCategoryId>("smileys");
    const pickerRef = useRef<HTMLDivElement | null>(null);

    useEffect(() => {
        const handleClick = (e: MouseEvent) => {
            if (pickerRef.current && !pickerRef.current.contains(e.target as Node)) onClose();
        };
        document.addEventListener("mousedown", handleClick);
        return () => document.removeEventListener("mousedown", handleClick);
    }, [onClose]);

    return (
        <motion.div ref={pickerRef} initial={{ opacity: 0, y: 12 }} animate={{ opacity: 1, y: 0 }}
            exit={{ opacity: 0, y: 12 }} transition={{ type: "spring", stiffness: 400, damping: 30 }} className="hidden lg:flex flex-col bg-card ml-auto border-border border-t rounded-b-xl max-w-md"
            style={{ height: 280 }}>
            {/* Emoji grid */}
            <div className="flex-1 px-3 py-2 overflow-y-auto hide-scrollbar">
                <div className="gap-1 grid grid-cols-8">
                    {EMOJI_DATA[activeCat].map((emoji, i) => (
                        <button
                            key={`${activeCat}-${i}`}
                            onClick={() => onPick(emoji)}
                            className="flex justify-center items-center hover:bg-primary/10 rounded-lg size-10 text-xl transition-colors"
                        >
                            {emoji}
                        </button>
                    ))}
                </div>
            </div>

            {/* Category bar */}
            <div className="flex items-center gap-1 px-2 py-1.5 border-border border-t overflow-x-auto scrollbar-none">
                {CATEGORIES.map((cat) => (
                    <button key={cat.id} onClick={() => setActiveCat(cat.id)}
                        className={`text-lg size-9 flex items-center justify-center rounded-lg transition-colors flex-shrink-0 ${activeCat === cat.id ? "bg-primary/40" : "hover:bg-muted/50"
                            }`} title={cat.name} aria-label={cat.name}>
                        {cat.label}
                    </button>
                ))}
            </div>
        </motion.div>
    );
}